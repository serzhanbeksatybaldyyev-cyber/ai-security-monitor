SPAM_WORDS = ["login", "verify", "secure", "bonus", "update", "confirm", "pay", "claim"]
LOOKALIKE = str.maketrans({"а": "a", "о": "o", "е": "e", "р": "p", "с": "c", "х": "x"})


def _spam_url(rng):
    brand = rng.choice(COMMON["brand"]).lower()
    tld = rng.choice(["example", "test", "example"])
    return f"http://{brand}-{rng.choice(SPAM_WORDS)}.{tld}/{rng.choice(SPAM_WORDS)}"


def _phone(rng):
    return f"+7 000 {rng.randint(100, 999)} {rng.randint(10, 99)} {rng.randint(10, 99)}"


def _fill(template, vocab, rng, spam, kk):
    used = {}

    def pick(match):
        field = match.group(1)
        base = re.sub(r"\d+$", "", field)
        if base == "url":
            return _spam_url(rng)
        if base == "phone" or base == "tel":
            return _phone(rng)
        if base == "n":
            return str(rng.randint(5, 55))
        if base == "amount":
            return rng.choice(AMOUNTS_KK if kk else AMOUNTS)
        options = vocab.get(base) or COMMON[base]
        taken = used.setdefault(base, set())
        choices = [value for value in options if value not in taken] or options
        value = rng.choice(choices)
        taken.add(value)
        if base == "day" and match.start() > 0:
            value = value[0].lower() + value[1:]
        return value

    text = re.sub(r"\{(\w+)\}", pick, template)
    pre = rng.choice(vocab["pre" if spam else "hpre"])
    post = rng.choice(vocab["post" if spam else "hpost"])
    if pre.endswith(", ") and not template.startswith("{") and text[:1].isupper():
        text = text[0].lower() + text[1:]
    text = f"{pre}{text}{post}".strip()
    return _vary(text, rng, spam)


def _vary(text, rng, spam):
    roll = rng.random()
    if spam:
        if roll < 0.12:
            words = text.split(" ")
            index = rng.randrange(len(words))
            words[index] = words[index].upper()
            text = " ".join(words)
        elif roll < 0.20:
            text = text.replace("!", "!!!") if "!" in text else text + "!!"
        elif roll < 0.28:
            words = text.split(" ")
            index = rng.randrange(len(words))
            words[index] = words[index].translate(LOOKALIKE)
            text = " ".join(words)
    else:
        if roll < 0.05:
            text = text.lower()
        elif roll < 0.10:
            text = text.rstrip(".!") + ".."
        elif roll < 0.13:
            text = text.replace(", ", ",")
    return text


def _generate(language, ham_templates, spam_templates, vocab, rng):
    kk = language == "kk"
    rows, seen = [], set()
    jobs = [("ham", index, template, None) for index, template in enumerate(ham_templates)]
    jobs += [("spam", index, template[1], template[0]) for index, template in enumerate(spam_templates)]
    quota = {"ham": TARGET_HAM, "spam": TARGET_SPAM}
    counts = {"ham": 0, "spam": 0}
    per_group = {job[:2]: 0 for job in jobs}
    rounds = 0
    while any(counts[kind] < quota[kind] for kind in quota) and rounds < 400:
        rounds += 1
        for kind, index, template, threat in jobs:
            if counts[kind] >= quota[kind]:
                continue
            text = _fill(template, vocab, rng, kind == "spam", kk)
            key = normalize_sms(text)
            if not key or key in seen:
                continue
            seen.add(key)
            counts[kind] += 1
            per_group[(kind, index)] += 1
            group = f"{language}-{kind}-{index + 1:02d}"
            rows.append({"text": text, "label": int(kind == "spam"), "language": language,
                         "threat_type": threat or "normal", "group": group, "label_author": AUTHOR})
    if counts != quota:
        raise RuntimeError(f"{language}: получено {counts}, нужно {quota}")
    rng.shuffle(rows)
    for number, row in enumerate(rows, 1):
        row["id"] = f"{language}-{number:05d}"
    return rows


def main() -> None:
    fields = ["id", "text", "label", "language", "threat_type", "group", "label_author"]
    for language, ham, spam, vocab in (("ru", HAM_RU, SPAM_RU, RU), ("kk", HAM_KK, SPAM_KK, KK)):
        rng = random.Random(f"{SEED}-{language}")
        rows = _generate(language, ham, spam, vocab, rng)
